def build_all_pdfs(output_dir: Path = DEFAULT_OUTPUT_DIR) -> list[Path]:
    """Generate all 4 built-in PDFs into *output_dir* and return their paths."""
    regular_font, bold_font = register_chinese_fonts()
    generated: list[Path] = []
    for spec in DOCUMENT_SPECS:
        generated.append(render_pdf(spec, output_dir, regular_font, bold_font))
    return generated


def main() -> None:
    parser = argparse.ArgumentParser(description="Build built-in KlackCraft KB PDFs.")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help="Target directory for generated PDFs (default: sz-agent/knowledge_docs)",
    )
    args = parser.parse_args()
    paths = build_all_pdfs(args.output_dir)
    for path in paths:
        print(f"Generated: {path}")


if __name__ == "__main__":
    main()
