def register_chinese_fonts() -> tuple[str, str]:
    """为 ReportLab 注册可读的内嵌中文字体（常规体与粗体）。"""
    registered = set(pdfmetrics.getRegisteredFontNames())
    for reg_name, reg_path, reg_idx, bold_name, bold_path, bold_idx in _FONT_CANDIDATES:
        reg_file = Path(reg_path)
        bold_file = Path(bold_path)
        if not reg_file.exists() or not bold_file.exists():
            continue
        try:
            if reg_name not in registered:
                kwargs = {"subfontIndex": reg_idx} if reg_idx is not None else {}
                pdfmetrics.registerFont(TTFont(reg_name, str(reg_file), **kwargs))
            if bold_name not in registered and bold_name != reg_name:
                kwargs = {"subfontIndex": bold_idx} if bold_idx is not None else {}
                pdfmetrics.registerFont(TTFont(bold_name, str(bold_file), **kwargs))
            return reg_name, bold_name
        except Exception:
            continue

    cid_name = "STSong-Light"
    if cid_name not in registered:
        pdfmetrics.registerFont(UnicodeCIDFont(cid_name))
    return cid_name, cid_name


def _escape_xml(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def _format_article_html(text: str) -> str:
    """加粗高亮条文起始编号（如“第二十五条”），同时保留正文整洁格式。"""
    escaped = _escape_xml(text)
    if "　" in escaped:
        head, tail = escaped.split("　", 1)
        if head.startswith("第") and "条" in head:
            return f"<b>{head}</b>　{tail}"
    return escaped


