def _draw_page_footer(canvas, doc) -> None:
    canvas.saveState()
    font_name = getattr(doc, "_footer_font", "Helvetica")
    canvas.setFont(font_name, 8.5)
    canvas.setFillColor(colors.HexColor("#6B7280"))
    canvas.drawCentredString(A4[0] / 2.0, 12 * mm, f"第 {doc.page} 页")
    canvas.restoreState()


def render_pdf(doc_spec: PdfDocumentSpec, output_dir: Path, regular_font: str, bold_font: str) -> Path:
    """将单个 PdfDocumentSpec 渲染为 PDF 文件并写入 output_dir，返回生成的文件路径。"""
    output_dir.mkdir(parents=True, exist_ok=True)
    out_path = output_dir / doc_spec.filename
    styles = _build_styles(regular_font, bold_font)

    doc = SimpleDocTemplate(
        str(out_path),
        pagesize=A4,
        leftMargin=20 * mm,
        rightMargin=20 * mm,
        topMargin=20 * mm,
        bottomMargin=20 * mm,
        title=doc_spec.title,
        author="咔嗒造物商城（KlackCraft）",
    )
    doc._footer_font = regular_font  # type: ignore[attr-defined]

    story = [
        Paragraph(_escape_xml(doc_spec.title), styles["title"]),
        Paragraph(_escape_xml(doc_spec.subtitle), styles["subtitle"]),
    ]

    usable_width = A4[0] - 40 * mm
    for section in doc_spec.sections:
        story.append(Paragraph(_escape_xml(section.heading), styles["h2"]))
        for item in section.items:
            story.append(Paragraph(_format_article_html(item), styles["body"]))
        if section.table:
            story.append(Spacer(1, 4))
            rows = []
            num_cols = len(section.table[0])
            col_widths = [usable_width * 0.22, usable_width * 0.34, usable_width * 0.44] if num_cols == 3 else [usable_width / num_cols] * num_cols
            for row_idx, row in enumerate(section.table):
                cell_style = styles["table_header"] if row_idx == 0 else styles["table_cell"]
                rows.append([Paragraph(_escape_xml(cell), cell_style) for cell in row])
            table = Table(rows, colWidths=col_widths, repeatRows=1)
            table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F3F4F6")),
                        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("LEFTPADDING", (0, 0), (-1, -1), 6),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                        ("TOPPADDING", (0, 0), (-1, -1), 5),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                    ]
                )
            )
            story.append(table)
            story.append(Spacer(1, 6))

    doc.build(story, onFirstPage=_draw_page_footer, onLaterPages=_draw_page_footer)
    return out_path


